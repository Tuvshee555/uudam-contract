import { AlignmentType, Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import type { ContractData } from "./types";

function p(text: string, options: { bold?: boolean; size?: number; center?: boolean; spacingAfter?: number } = {}) {
  return new Paragraph({
    alignment: options.center ? AlignmentType.CENTER : undefined,
    spacing: { after: options.spacingAfter ?? 160 },
    children: [new TextRun({ text, bold: options.bold, size: options.size ?? 22 })]
  });
}

function h2(text: string) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text, bold: true, size: 24 })]
  });
}

